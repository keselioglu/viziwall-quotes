def main():
    db = SessionLocal()
    updated, missing = 0, []
    try:
        for idx, (quote_number, month_year) in enumerate(ROWS):
            quotation = db.query(Quotation).filter(Quotation.quote_number == quote_number).first()
            if not quotation:
                missing.append(quote_number)
                continue

            month, year = month_year.split("/")
            base = datetime(int(year), int(month), 1)
            # Small per-row offset preserves stable ordering among quotes sharing a month.
            created = base + timedelta(seconds=idx)

            quotation.created_at = created
            quotation.quotation_date_text = month_year
            updated += 1

        db.commit()
        print(f"Updated {updated} quotation(s).")
        if missing:
            print(f"Not found in DB: {missing}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
